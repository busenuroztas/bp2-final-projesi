    private void LoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginActionPerformed
        
        String userName = userNameTextField.getText();
        String password = passwordTextField.getText();
        
        boolean baglandiMi = KullaniciGirisBaglama.login(userName, password);
        
        if (baglandiMi) {
            JOptionPane.showMessageDialog(null, "Login successfully");
            suankiKullanici = userNameTextField.getText();
            AnaEkran anaEkran = new AnaEkran();
            anaEkran.setVisible(true);
            this.dispose();
        } else if (userName.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Username or password cannot be blank. Please enter all required information.", "Attention", JOptionPane.WARNING_MESSAGE);
        } else if (baglandiMi == false) {
            JOptionPane.showMessageDialog(null, "Username or password is incorrect. Please try again!", "Attention", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_LoginActionPerformed

    
    
