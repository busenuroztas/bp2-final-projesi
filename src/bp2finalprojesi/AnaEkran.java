    private void kullaniciBilgileriniGetir() {
        try {
            String kullaniciAdi;

            if (UserLogin.suankiKullanici != null) {
                kullaniciAdi = UserLogin.suankiKullanici;
            } else {
                kullaniciAdi = AdminLogin.suankiKullanici;
            }

            java.sql.Connection conn = VeriTabaniConnection.connect();
            String sql = "SELECT * FROM users WHERE username=?";
            java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, kullaniciAdi);

            java.sql.ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                fullNameTextField.setText(rs.getString("name") + " " + rs.getString("surname"));
                UsernameTextField.setText(rs.getString("username"));
                emailTextField.setText(rs.getString("email"));
                roleTextField.setText(rs.getString("role"));
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Kullanici bilgileri getirilemedi.");
        }
    }

    
    
