    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed

        try {
            String amount = amountTextField.getText().trim();
            String category = (String) categoryCombobox.getSelectedItem();
            String currency = (String) currencyCombobox.getSelectedItem();
            String type = incomeRadioButton.isSelected() ? "Income" : "Expense";
            String description = descriptionTextArea.getText().trim();
            java.util.Date utilDate = (java.util.Date) dateJSpinner.getValue();
            java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

            String transactor = (UserLogin.suankiKullanici != null)
                    ? UserLogin.suankiKullanici
                    : AdminLogin.suankiKullanici;

            java.sql.Connection conn = VeriTabaniConnection.connect();
            String sql = "INSERT INTO transactions (date, type, category, amount, currency, description, transactor) VALUES (?, ?, ?, ?, ?, ?, ?)";
            java.sql.PreparedStatement stmt = conn.prepareStatement(sql, java.sql.Statement.RETURN_GENERATED_KEYS);

            stmt.setDate(1, sqlDate);
            stmt.setString(2, type);
            stmt.setString(3, category);
            stmt.setDouble(4, Double.parseDouble(amount));
            stmt.setString(5, currency);
            stmt.setString(6, description);
            stmt.setString(7, transactor);

            int affected = stmt.executeUpdate();
            if (affected > 0) {
                java.sql.ResultSet keys = stmt.getGeneratedKeys();
                if (keys.next()) {
                    int id = keys.getInt(1);

                    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
                    model.addRow(new Object[]{id, sqlDate.toString(), type, category, amount, currency, description});

                    javax.swing.JOptionPane.showMessageDialog(null, "Transaction added successfully.");
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(null, "Error");
        }

    }//GEN-LAST:event_addButtonActionPerformed

    
    
    
    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(null, "Please select a transaction to delete.");
            return;
        }

        int onay = javax.swing.JOptionPane.showConfirmDialog(null, "Are you sure you want to delete this transaction?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        if (onay == javax.swing.JOptionPane.YES_OPTION) {
            try {
                int id = (int) jTable1.getValueAt(selectedRow, 0);

                java.sql.Connection conn = VeriTabaniConnection.connect();
                java.sql.PreparedStatement stmt = conn.prepareStatement("DELETE FROM transactions WHERE id=?");
                stmt.setInt(1, id);
                stmt.executeUpdate();

                javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
                model.removeRow(selectedRow);

                javax.swing.JOptionPane.showMessageDialog(null, "Transaction deleted.");
            } catch (Exception e) {
                e.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(null, "Error");
            }
        }

    }//GEN-LAST:event_deleteButtonActionPerformed


    
    
    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(null, "Please select a transaction to update.");
            return;
        }

        try {
            int id = (int) jTable1.getValueAt(selectedRow, 0);
            String amount = amountTextField.getText().trim();
            String category = (String) categoryCombobox.getSelectedItem();
            String currency = (String) currencyCombobox.getSelectedItem();
            String type = incomeRadioButton.isSelected() ? "Income" : "Expense";
            String description = descriptionTextArea.getText().trim();
            java.util.Date utilDate = (java.util.Date) dateJSpinner.getValue();
            java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

            java.sql.Connection conn = VeriTabaniConnection.connect();
            String sql = "UPDATE transactions SET date=?, type=?, category=?, amount=?, currency=?, description=? WHERE id=?";
            java.sql.PreparedStatement stmt = conn.prepareStatement(sql);

            stmt.setDate(1, sqlDate);
            stmt.setString(2, type);
            stmt.setString(3, category);
            stmt.setDouble(4, Double.parseDouble(amount));
            stmt.setString(5, currency);
            stmt.setString(6, description);
            stmt.setInt(7, id);

            stmt.executeUpdate();

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
            model.setValueAt(sqlDate.toString(), selectedRow, 1);
            model.setValueAt(type, selectedRow, 2);
            model.setValueAt(category, selectedRow, 3);
            model.setValueAt(amount, selectedRow, 4);
            model.setValueAt(currency, selectedRow, 5);
            model.setValueAt(description, selectedRow, 6);

            javax.swing.JOptionPane.showMessageDialog(null, "Transaction updated.");
        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(null, "Error");
        }
    }//GEN-LAST:event_updateButtonActionPerformed

    
    
