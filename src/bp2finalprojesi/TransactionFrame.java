    private void verileriViewTablosunaYukle() {
        try {
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) viewTable.getModel();
            model.setRowCount(0);

            java.sql.Connection con = VeriTabaniConnection.connect();
            String sql = "SELECT * FROM transactions";
            java.sql.PreparedStatement stmt = con.prepareStatement(sql);
            java.sql.ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                int id = rs.getInt("id");
                String date = rs.getDate("date").toString();
                String type = rs.getString("type");
                String category = rs.getString("category");
                String amount = String.valueOf(rs.getDouble("amount"));
                String currency = rs.getString("currency");
                String description = rs.getString("description");

                model.addRow(new Object[]{id, date, type, category, amount, currency, description});
            }

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(null, "Hata olustu.");
        }
    }


