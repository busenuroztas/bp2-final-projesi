    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        try {
            String name = nameTextField.getText().trim();
            String surname = surnameTextField.getText().trim();
            String username = usernameTextField.getText().trim();
            String email = emailTextField.getText().trim();
            String password = new String(passwordField.getPassword());
            String role = roleComboBox.getSelectedItem().toString();

            if (!email.matches("^[\\w.-]+@[\\w.-]+\\.\\w{2,}$")
                    || !username.matches("^[a-zA-Z0-9_]{4,}$")
                    || !password.matches("^.{6,}$")) {
                JOptionPane.showMessageDialog(null, "Check format (email/username/password)");
                return;
            }

            Connection baglanti = (Connection) VeriTabaniConnection.connect();
            PreparedStatement stmt = baglanti.prepareStatement(
                    "INSERT INTO users (name, surname, username, email, password, role) VALUES (?, ?, ?, ?, ?, ?)");
            stmt.setString(1, name);
            stmt.setString(2, surname);
            stmt.setString(3, username);
            stmt.setString(4, email);
            stmt.setString(5, password);
            stmt.setString(6, role);
            stmt.executeUpdate();

            JOptionPane.showMessageDialog(null, "User added.");
            verileriTabloyaYukle();

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error");
        }
    }//GEN-LAST:event_addButtonActionPerformed

    
    
    
    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Select a user to update.");
            return;
        }
        int id = (int) jTable1.getValueAt(selectedRow, 0);
        try {
            String name = nameTextField.getText().trim();
            String surname = surnameTextField.getText().trim();
            String username = usernameTextField.getText().trim();
            String email = emailTextField.getText().trim();
            String password = new String(passwordField.getPassword());
            String role = roleComboBox.getSelectedItem().toString();

            Connection baglanti = (Connection) VeriTabaniConnection.connect();
            PreparedStatement stmt = baglanti.prepareStatement(
                    "UPDATE users SET name=?, surname=?, username=?, email=?, password=?, role=? WHERE id=?");
            stmt.setString(1, name);
            stmt.setString(2, surname);
            stmt.setString(3, username);
            stmt.setString(4, email);
            stmt.setString(5, password);
            stmt.setString(6, role);
            stmt.setInt(7, id);
            stmt.executeUpdate();

            JOptionPane.showMessageDialog(null, "User updated.");
            verileriTabloyaYukle();
            
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error");
        }
    }//GEN-LAST:event_updateButtonActionPerformed

    
    
    
    
    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Select a user to delete.");
            return;
        }
        
        int onay = JOptionPane.showConfirmDialog(null, "Are you sure?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (onay != JOptionPane.YES_OPTION) {
            return;
        }

        int id = (int) jTable1.getValueAt(selectedRow, 0);
        
        try {
            Connection baglanti = (Connection) VeriTabaniConnection.connect();
            PreparedStatement stmt = baglanti.prepareStatement("DELETE FROM users WHERE id = ?");
            stmt.setInt(1, id);
            stmt.executeUpdate();
            
            JOptionPane.showMessageDialog(null, "User deleted.");
            verileriTabloyaYukle();
            
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error");
        }
    }//GEN-LAST:event_deleteButtonActionPerformed

    
    
